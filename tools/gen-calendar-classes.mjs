// Emits libs/ui/calendar/calendar.classes.ts from the REA captures of the calendar demos.
//   node tools/gen-calendar-classes.mjs <date-picker-capture.txt> <calendar-capture.txt>
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const [, , pickerCapture, calendarCapture] = process.argv;
const html = (file) =>
  JSON.parse(fs.readFileSync(file, 'utf8')).normalized_result.steps.at(-1).artifacts.dom.value.text
    .replace(/&amp;/g, '&')
    .replace(/&gt;/g, '>')
    .replace(/&lt;/g, '<');
const strip = (cls) =>
  cls
    .split(/\s+/)
    .filter((t) => t && !/^rdp-/.test(t) && !/^cn-/.test(t))
    .map((t) => t.replace(/(^|:)-?(pl|pr)-/, (m, p, d) => `${p}${d === 'pl' ? 'ps' : 'pe'}-`).replace(/rounded-r-/g, 'rounded-e-').replace(/rounded-l-/g, 'rounded-s-'))
    .join(' ');

const picker = html(pickerCapture);
const cal = html(calendarCapture);
const tag = /<([a-z0-9]+)((?:\s+[^\s=>"']+(?:="[^"]*")?)*)\s*\/?>/g;
const classOf = (attrs) => (attrs.match(/class="([^"]*)"/) || [])[1] || '';

const found = {};
const want = (key, re, tagName) => {
  for (const m of picker.matchAll(tag)) {
    if (tagName && m[1] !== tagName) continue;
    const c = classOf(m[2]);
    if (re.test(c) && !found[key]) found[key] = strip(c);
  }
};
want('calendar', /rdp-root/);
want('months', /rdp-months/);
want('nav', /rdp-nav/);
want('month', /rdp-month(?!\w|_)/);
want('caption', /rdp-month_caption/);
want('captionLabel', /rdp-caption_label/);
want('grid', /rdp-month_grid/);
want('weekdays', /rdp-weekdays/);
want('weekday', /rdp-weekday(?!s)/);
want('week', /rdp-week(?!\w|s|day)/);

// nav button: first <button> with aria-label "Go to the Previous Month"
for (const m of picker.matchAll(tag)) {
  if (m[1] === 'button' && /Previous Month/.test(m[2])) {
    found.navButton = strip(classOf(m[2]));
    break;
  }
}

// day cells / day button
const td = {};
const btn = {};
for (const m of cal.matchAll(tag)) {
  if (!/data-day/.test(m[2])) continue;
  const flags = (m[2].match(/ data-(today|outside|selected|disabled|hidden)="true"/g) || []).map((x) => x.match(/data-(\w+)/)[1]).sort().join('+') || 'base';
  if (m[1] === 'td') td[flags] ??= strip(classOf(m[2]));
  else if (m[1] === 'button') btn.base ??= strip(classOf(m[2]));
}

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
let out = `// GENERATED by tools/gen-calendar-classes.mjs from docs/evidence (REA captures of the calendar + date-picker demos).\n// rdp-*/cn-* hook classes removed; pl/pr/rounded-l/rounded-r converted to logical.\n\n`;
for (const k of ['calendar', 'months', 'nav', 'navButton', 'month', 'caption', 'captionLabel', 'grid', 'weekdays', 'weekday', 'week'])
  out += `export const calendar${k[0].toUpperCase()}${k.slice(1)}Class =\n  ${q(found[k] ?? '')};\n\n`;
out += `/** Day cell (td) classes by state, as observed. */\nexport const calendarDayCellClass: Record<string, string> = {\n${Object.entries(td).map(([k, v]) => `  ${q(k)}: ${q(v)},`).join('\n')}\n};\n\n`;
out += `/** Day button: one string for every state; selection/range/today are driven by data-* attributes inside it. */\nexport const calendarDayButtonClass =\n  ${q(btn.base ?? '')};\n`;
fs.writeFileSync(path.join(root, 'libs/ui/calendar/calendar.classes.ts'), out);
console.log(Object.keys(found), Object.keys(td), (btn.base ?? '').length);
