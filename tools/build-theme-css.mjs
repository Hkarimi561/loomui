// Builds libs/ui/styles/loomui.css — the consumer-facing theme: shadcn tokens (light + .dark), @theme mapping, the custom
// variants our class strings rely on, overlay/animation helpers, toast CSS and optional accent presets.
// Source of truth stays projects/playground/src/styles.css (sections before "Showcase polish" and the accent presets).
//   node tools/build-theme-css.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = fs.readFileSync(path.join(root, 'projects/playground/src/styles.css'), 'utf8');

const start = src.indexOf('@custom-variant dark');
const polish = src.indexOf('/* ---------- Showcase polish');
const accents = src.indexOf('/* ---------- Accent presets');
if (start < 0 || polish < 0 || accents < 0) throw new Error('styles.css markers not found');
const accentEnd = src.indexOf('/* ---------- Animated theme', accents) >= 0 ? src.indexOf('/* ---------- Animated theme', accents) : src.length;

const toast = fs.readFileSync(path.join(root, 'libs/ui/toast/toast.css'), 'utf8');

const css = `/*!
 * @loomui/ui theme — generated by tools/build-theme-css.mjs. Import once in your global stylesheet AFTER tailwindcss:
 *
 *   @import 'tailwindcss';
 *   @import '@loomui/ui/styles/loomui.css';
 *
 *   (class scanning of the package is configured inside this file via @source)
 *
 * Add class="dark" to <html> for dark mode; add e.g. class="theme-blue" for an accent preset.
 */
@import 'tw-animate-css';
@import '@angular/cdk/overlay-prebuilt.css';

/* Let Tailwind scan this package's compiled components for class names. */
@source "../";

${src.slice(start, polish).trim()}

${src.slice(accents, accentEnd).trim()}

/* ---- Toast (ui-toaster) ---- */
${toast.trim()}
`;
fs.mkdirSync(path.join(root, 'libs/ui/styles'), { recursive: true });
fs.writeFileSync(path.join(root, 'libs/ui/styles/loomui.css'), css);
console.log('wrote libs/ui/styles/loomui.css', css.length, 'bytes');
