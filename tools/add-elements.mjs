// Adds a custom-element form to every Loom UI directive/component:   [uiDialogContent]  →  [uiDialogContent], ui-dialog-content
// and applies `hostDirectives: [UiElementHost]`, which gives the custom element the semantics native tags have for free
// (role, tabindex, Enter/Space activation, link/label behavior, display). Idempotent — safe to run after any generator.
//   node tools/add-elements.mjs
// Also writes libs/ui/utils/elements.ts (alias → origin tag) and projects/playground/src/app/elements.generated.ts (attr → alias).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lib = path.join(root, 'libs/ui');

/** Native controls that cannot be turned into a custom element — they get hand-written wrapper components instead. */
const WRAPPER_TAGS = new Set(['input', 'textarea', 'select', 'option', 'optgroup', 'img']);
const SKIP_DIRS = new Set(['utils', 'icon', 'styles']);

const kebab = (attr) =>
  attr
    .replace(/^ui/, 'ui-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();

const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
    if (e.isDirectory()) return SKIP_DIRS.has(e.name) ? [] : walk(path.join(d, e.name));
    return [path.join(d, e.name)];
  });

/**
 * Class strings written for a direct `svg` child (`has-[>svg]:grid-cols-…`, `[&>svg]:size-3!`) get a `ui-icon` twin, so the
 * same layout works when the icon is the <ui-icon> custom element. Idempotent.
 */
function iconTwins(src) {
  const re = /(^|[\s'"`])((?:[a-z0-9/-]+:)*(?:group-)?(?:has-\[>svg\]|\[&>svg\])[^\s'"`]*)(?=[\s'"`]|$)/gm;
  return src.replace(re, (m, pre, token, offset, whole) => {
    if (token.includes(':not(')) return m;
    const twin = token.replace('>svg', '>ui-icon');
    // skip when the twin is already present on the same line (idempotency)
    const lineStart = whole.lastIndexOf('\n', offset) + 1;
    const lineEnd = whole.indexOf('\n', offset);
    if (whole.slice(lineStart, lineEnd < 0 ? undefined : lineEnd).includes(twin)) return m;
    return `${pre}${token} ${twin}`;
  });
}

const origins = {}; // alias -> origin tag
const attrs = {}; // attr -> alias
const skipped = [];
let changedFiles = 0;

for (const file of walk(lib).filter((f) => f.endsWith('.ts') && !/index\.ts$|\.classes\.ts$/.test(f))) {
  let s = fs.readFileSync(file, 'utf8');
  const before = s;
  let usedHost = false;

  s = s.replace(/(@(?:Directive|Component)\(\{\s*)selector:\s*'([^']+)'(,?)/g, (full, head, sel, comma) => {
    const parts = sel.split(',').map((p) => p.trim());
    const parsed = parts.map((p) => p.match(/^([a-z][a-z0-9-]*)?\[(ui[A-Za-z0-9]+)\]$/));
    if (parsed.some((m) => !m)) return full; // already an element selector, or exotic — leave alone
    const first = parsed[0];
    const attrName = first[2];
    const tags = parsed.map((m) => m[1] ?? '');
    if (tags.some((t) => WRAPPER_TAGS.has(t))) {
      skipped.push(`${path.relative(root, file)} :: ${sel}`);
      return full;
    }
    const alias = kebab(attrName);
    // origin = the first concrete tag, else unknown
    origins[alias] = tags.find((t) => t) ?? '';
    attrs[attrName] = alias;
    usedHost = true;
    return `${head}selector: '${sel}, ${alias}',${comma ? '' : ''} hostDirectives: [UiElementHost],`;
  });

  // already-transformed selectors (idempotency): record them for the maps
  for (const m of s.matchAll(/selector:\s*'([^']+),\s*(ui-[a-z0-9-]+)',\s*hostDirectives: \[UiElementHost\]/g)) {
    const attr = m[1].match(/\[(ui[A-Za-z0-9]+)\]/)?.[1];
    if (attr && !attrs[attr]) {
      attrs[attr] = m[2];
      const tag = m[1].split(',')[0].trim().match(/^([a-z][a-z0-9-]*)\[/)?.[1] ?? '';
      origins[m[2]] = tag;
    }
    usedHost = true;
  }

  s = iconTwins(s);

  if (usedHost && !/\bUiElementHost\b[^;]*from '@loomui-ng\/ui\/utils'/.test(s)) {
    const re = /^import[\s\S]*?from\s+'[^']+';\n/gm;
    let m;
    let end = 0;
    while ((m = re.exec(s))) end = m.index + m[0].length;
    s = s.slice(0, end) + "import { UiElementHost } from '@loomui-ng/ui/utils';\n" + s.slice(end);
  }
  if (s !== before) {
    fs.writeFileSync(file, s);
    changedFiles++;
  }
}

/** Wrapper components (native controls) — their attribute form maps to an element too. */
const WRAPPER_ATTRS = {
  uiInput: 'ui-input',
  uiTextarea: 'ui-textarea',
  uiInputGroupControl: 'ui-input-group-control',
  uiAvatarImage: 'ui-avatar-image',
  uiCommandInput: 'ui-command-input',
  uiComboboxInput: 'ui-combobox-input',
  uiNativeSelect: 'ui-native-select',
};
Object.assign(attrs, WRAPPER_ATTRS);

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  path.join(lib, 'utils/elements.ts'),
  `// GENERATED by tools/add-elements.mjs — alias (custom element) → the native tag the directive was written for.\n// Used by UiElementHost to give custom elements the roles/behavior of their native counterparts.\nexport const ELEMENT_ORIGIN: Record<string, string> = ${JSON.stringify(sorted(origins), null, 2)};\n`,
);
fs.writeFileSync(
  path.join(root, 'projects/playground/src/app/elements.generated.ts'),
  `// GENERATED by tools/add-elements.mjs — directive attribute → custom element, used to show the element form of snippets.\nexport const ELEMENT_ATTRS: Record<string, string> = ${JSON.stringify(sorted(attrs), null, 2)};\n`,
);
fs.writeFileSync(path.join(root, 'tools/elements-map.json'), JSON.stringify(sorted(attrs), null, 2) + '\n');
console.log(`elements: ${Object.keys(origins).length} aliases, ${changedFiles} files changed, ${skipped.length} wrapper-only selectors`);
for (const s of skipped) console.log('  wrapper needed:', s);
