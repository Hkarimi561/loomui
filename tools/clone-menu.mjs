// Derives the shared menu parts (items, checkbox/radio, sub-menus, label, separator, shortcut, group) of Context Menu and
// Menubar from libs/ui/dropdown-menu/dropdown-menu.ts, swapping names and class constants.
//   node tools/clone-menu.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = fs.readFileSync(path.join(root, 'libs/ui/dropdown-menu/dropdown-menu.ts'), 'utf8');
const start = src.indexOf("@Directive({\n  selector: '[uiDropdownMenuItem]'");
const end = src.indexOf('export const UI_DROPDOWN_MENU');
if (start < 0 || end < 0) throw new Error('markers not found in dropdown-menu.ts');
const shared = src.slice(start, end);

const TARGETS = {
  'context-menu': {
    Pascal: 'ContextMenu',
    camel: 'contextMenu',
    kebab: 'context-menu',
    sub: { side: 'right' },
    classes: {
      ITEM: 'contextMenuItemClass',
      SUB_TRIGGER: 'contextMenuSubTriggerClass',
      CHECKBOX: 'contextMenuCheckboxItemClass',
      RADIO: 'contextMenuRadioItemClass',
      LABEL: 'contextMenuLabelClass',
      SEPARATOR: 'contextMenuSeparatorClass',
      SHORTCUT: 'contextMenuShortcutClass',
      CONTENT: 'contextMenuContentClass',
    },
    importFrom: './context-menu',
  },
  menubar: {
    Pascal: 'Menubar',
    camel: 'menubar',
    kebab: 'menubar',
    sub: { side: 'right' },
    classes: {
      ITEM: 'menubarItemClass',
      SUB_TRIGGER: 'menubarSubTriggerClass',
      CHECKBOX: null, // not captured: derived from context-menu with names swapped
      RADIO: null,
      LABEL: null,
      SEPARATOR: 'menubarSeparatorClass',
      SHORTCUT: 'menubarShortcutClass',
      CONTENT: 'menubarContentClass',
    },
    importFrom: './menubar',
  },
};

for (const [name, t] of Object.entries(TARGETS)) {
  const rename = (s) =>
    s
      .replace(/UiDropdownMenu/g, `Ui${t.Pascal}`)
      .replace(/uiDropdownMenu/g, `ui${t.Pascal}`)
      .replace(/dropdown-menu/g, t.kebab);
  const body = rename(shared);
  const c = t.classes;
  const swap = (cls) => `${cls}.replace(/context-menu/g, '${t.kebab}')`;
  const ref = (key, fallback) => (c[key] ? c[key] : swap(fallback));
  const header = `// GENERATED by tools/clone-menu.mjs from dropdown-menu.ts — hand-edit only the root/trigger/content in ./${name}.ts.\n` +
    `import {\n  booleanAttribute,\n  ChangeDetectionStrategy,\n  Component,\n  computed,\n  Directive,\n  forwardRef,\n  inject,\n  input,\n  model,\n} from '@angular/core';\n` +
    `import { cn } from '@loomui-ng/ui/utils';\n` +
    `import {\n  UI_MENU_CTX,\n  UI_MENU_ITEM,\n  UI_MENU_SUB,\n  UiMenuItemBase,\n  UiMenuSubBase,\n  UiMenuSubTriggerBase,\n  UiMenuContentBase,\n  UiMenuSelectEvent,\n} from '@loomui-ng/ui/utils';\n` +
    `import { type Align } from '@loomui-ng/ui/utils';\nimport { contentChildren } from '@angular/core';\nimport { UiIconSvg } from '@loomui-ng/ui/icon';\n` +
    (name === 'menubar'
      ? `import { contextMenuCheckboxItemClass, contextMenuLabelClass, contextMenuRadioItemClass, contextMenuContentClass } from '@loomui-ng/ui/context-menu';\n`
      : '') +
    `import { ${Object.values(c).filter(Boolean).join(', ')} } from '${t.importFrom}';\n\n` +
    `export { UiMenuSelectEvent };\n\n` +
    `const ITEM_CLASS = ${ref('ITEM')};\nconst SUB_TRIGGER_CLASS = ${ref('SUB_TRIGGER')};\n` +
    `const CHECKBOX_CLASS = ${c.CHECKBOX ?? swap('contextMenuCheckboxItemClass')};\nconst RADIO_CLASS = ${c.RADIO ?? swap('contextMenuRadioItemClass')};\n` +
    `const LABEL_CLASS = ${c.LABEL ?? swap('contextMenuLabelClass')};\nconst SEPARATOR_CLASS = ${ref('SEPARATOR')};\nconst SHORTCUT_CLASS = ${ref('SHORTCUT')};\n` +
    `const CONTENT_CLASS = ${ref('CONTENT')};\n\n`;
  fs.writeFileSync(path.join(root, 'libs/ui', name, `${name}.shared.ts`), header + body + `\nexport const ${name.toUpperCase().replace(/-/g, '_')}_SHARED = [\n  Ui${t.Pascal}Item,\n  Ui${t.Pascal}CheckboxItem,\n  Ui${t.Pascal}RadioGroup,\n  Ui${t.Pascal}RadioItem,\n  Ui${t.Pascal}Sub,\n  Ui${t.Pascal}SubTrigger,\n  Ui${t.Pascal}SubContent,\n  Ui${t.Pascal}Label,\n  Ui${t.Pascal}Separator,\n  Ui${t.Pascal}Shortcut,\n  Ui${t.Pascal}Group,\n] as const;\n`);
  console.log(`cloned -> libs/ui/${name}/${name}.shared.ts`);
}

// Keep the custom-element form (alias selector + UiElementHost) on regenerated files.
await import('./add-elements.mjs');
