// Extracts import line, usage snippet, API table and parts from libs/ui/<c>/README.md into
// projects/playground/src/app/docs.generated.ts so the showcase can render a Code tab and an API table.
//   node tools/gen-showcase-docs.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lib = path.join(root, 'libs/ui');
const out = {};

for (const c of fs.readdirSync(lib)) {
  const file = path.join(lib, c, 'README.md');
  if (!fs.existsSync(file) || c === 'utils') continue;
  const md = fs.readFileSync(file, 'utf8');
  const blocks = [...md.matchAll(/```(\w*)\n([\s\S]*?)```/g)].map((m) => ({ lang: m[1], code: m[2].trimEnd() }));
  const ts = blocks.find((b) => b.lang === 'ts');
  const html = blocks.find((b) => b.lang === 'html');
  const importLine = ts?.code.split('\n').find((l) => l.startsWith('import ')) ?? '';
  // Button's README keeps everything in one ts block (full component) — show that as usage.
  const usage = html ? html.code : ts && ts.code.includes('@Component') ? ts.code : '';
  const rows = [];
  const lines = md.split('\n');
  const start = lines.findIndex((l) => /^\|.*\|$/.test(l) && /Input|Values|Type/.test(l));
  if (start >= 0) {
    for (let i = start + 2; i < lines.length && /^\|/.test(lines[i]); i++) {
      const cells = lines[i].split(/(?<!\\)\|/).slice(1, -1).map((s) => s.trim().replace(/\\\|/g, '|').replace(/`/g, ''));
      if (cells.length >= 2) rows.push([cells[0], cells[1], cells[2] ?? '']);
    }
  }
  const partsLine = lines.find((l) => /^Parts( \(selectors\))?:/.test(l));
  const parts = partsLine ? [...partsLine.matchAll(/`([^`]+)`/g)].map((m) => m[1]) : [];
  out[c] = { importLine, usage, api: rows, parts };
}

const body = `// GENERATED by tools/gen-showcase-docs.mjs from libs/ui/*/README.md — do not edit.
export interface ComponentDocs {
  importLine: string;
  usage: string;
  api: [string, string, string][];
  parts: string[];
}

export const DOCS: Record<string, ComponentDocs> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, 'projects/playground/src/app/docs.generated.ts'), body);
console.log('docs for', Object.keys(out).length, 'components;', Object.values(out).filter((d) => !d.usage).length, 'without usage;', Object.values(out).filter((d) => !d.api.length).length, 'without api');
